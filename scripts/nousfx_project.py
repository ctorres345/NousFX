"""Project mode: the per-tool files of one repo (NFX-46). Used by nousfx_sync.py --project.

What a repo gets, besides its MCP files (nousfx_mcp.py) and agy plugin manifest (nousfx_agy.py):

  AGENTS.md            the neutral rules, a short stub only when the repo has none
  CLAUDE.md            a stub that imports AGENTS.md, only when the repo has none
  .githooks/pre-push   the advisory pre-push gate (claude/githooks/pre-push), generated
  .agents/skills       a link to ../.claude/skills, when the repo keeps its own skills there
  (note only)          a line when .nousfx/project.toml has no [check] command (NFX-54): the review gate
                       cannot record a review without one. Sync never invents a command.

Rules:
- A file the repo wrote by hand is never replaced on its own. Sync shows the diff, says how to confirm
  (--yes-replace NAME), and carries on with the rest.
- CLAUDE.md and AGENTS.md belong to the repo once they exist. CLAUDE.md only has to import AGENTS.md.
- The review gate itself is not copied into the repo: a copy there is code under review, and a branch could
  edit it to pass. The pre-push hook reads it from the user's home, and agy reads it from the global plugin.
- Nothing personal is written: the stubs and the hook are fixed text.
"""
import difflib
import os
import tomllib

GENERATED = "generated by nousfx_sync"
IMPORT = "@AGENTS.md"
AGENTS_STUB = (f"<!-- Created by nousfx_sync. This file is yours: write the repo's rules here. "
               "Every tool reads it. -->\n\n# Agent rules\n\nBuild, test and workflow rules for this repo go here.\n")
CLAUDE_STUB = (f"{IMPORT}\n\n<!-- Created by nousfx_sync. This file is yours: add notes only Claude Code needs "
               "below the import. -->\n")
HOOK_REL = os.path.join(".githooks", "pre-push")
HOOK_SOURCE = os.path.join("claude", "githooks", "pre-push")
SKILLS_LINK_REL = os.path.join(".agents", "skills")
SKILLS_TARGET_REL = os.path.join(".claude", "skills")
CHECK_REL = os.path.join(".nousfx", "project.toml")
NO_CHECK_NOTE = ("note: no check command in {path}. The review gate refuses to record a review without one "
                 "(or an approved --skip). Add:\n  [check]\n  command = \"<your test command>\"\n"
                 "The project-setup skill can propose one for this stack.")


class ProjectPlan:
    def __init__(self):
        self.files = {}   # absolute path -> text sync will write
        self.links = []   # (absolute path, target) to create
        self.notes = []   # lines to print in every mode (hand-written files left alone, with their diff)
        self.executable = set()  # written files that must be executable


def _read(path):
    """The text, or None when absent. Raises OSError or UnicodeDecodeError for anything else."""
    try:
        with open(path, encoding="utf-8") as f:
            return f.read()
    except FileNotFoundError:
        return None


def _diff(path, old, new):
    return "".join(difflib.unified_diff(old.splitlines(keepends=True), new.splitlines(keepends=True),
                                        fromfile=path, tofile=path + " (proposed)"))


def _hook_text(repo, SyncError):
    src = os.path.join(repo, HOOK_SOURCE)
    text = _read(src)
    if text is None:
        raise SyncError(f"missing pre-push hook source: {src}", 2)
    first, _, rest = text.partition("\n")
    return (f"{first}\n# {GENERATED} from NousFX {HOOK_SOURCE.replace(os.sep, '/')}. "
            f"Do not edit; change the source and re-run.\n{rest}")


def _has_check_command(path):
    """True when the file holds [check] command = "<text>". Unreadable or invalid counts as no."""
    try:
        text = _read(path)
        table = tomllib.loads(text).get("check") if text else None
    except (OSError, UnicodeDecodeError, tomllib.TOMLDecodeError):
        return False
    command = table.get("command") if isinstance(table, dict) else None
    return isinstance(command, str) and bool(command.strip())


def _hand_written(plan, path, old, new, name, how):
    plan.notes.append(f"left alone (hand-written): {path}. Pass --yes-replace {name} to {how}. Proposed change:\n"
                      f"{_diff(path, old, new)}".rstrip("\n"))


def plan_project(repo, project, SyncError, yes_replace=()):
    """The repo files sync owns or may create, as a ProjectPlan. Reads the repo, writes nothing."""
    try:
        return _plan(repo, project, SyncError, yes_replace)
    except (OSError, UnicodeDecodeError) as e:
        raise SyncError(f"cannot read {getattr(e, 'filename', None) or project} ({type(e).__name__}); "
                        "fix it by hand and run sync again. Nothing was written.", 2)


def _plan(repo, project, SyncError, yes_replace):
    p = ProjectPlan()
    agents = os.path.join(project, "AGENTS.md")
    if not os.path.lexists(agents):  # existence only: what an existing AGENTS.md holds is the repo's business
        p.files[agents] = AGENTS_STUB

    claude = os.path.join(project, "CLAUDE.md")
    if os.path.islink(claude):  # never read through a link: it may point outside the repo
        if os.path.realpath(claude) != os.path.realpath(agents):  # a link to AGENTS.md already does the job
            p.notes.append(f"left alone (CLAUDE.md is a symlink to somewhere else, not read): {claude}")
    else:
        old = _read(claude)
        if old is None:
            p.files[claude] = CLAUDE_STUB
        elif IMPORT not in old.split():  # whole word: "@AGENTS.md" inside a longer path does not count
            new = f"{IMPORT}\n\n{old}"
            if "CLAUDE.md" in yes_replace:
                p.files[claude] = new
            else:
                _hand_written(p, claude, old, new, "CLAUDE.md", "add the import line at the top")

    hook = os.path.join(project, HOOK_REL)
    new = _hook_text(repo, SyncError)
    if os.path.islink(hook) or os.path.islink(os.path.dirname(hook)):  # never read through a link
        p.notes.append(f"left alone (the hook or its folder is a symlink, not read): {hook}")
    else:
        old = _read(hook)
        if old is None or old == new or GENERATED in old or ".githooks/pre-push" in yes_replace:
            p.files[hook] = new
            p.executable.add(hook)
        else:
            _hand_written(p, hook, old, new, ".githooks/pre-push", "replace it with the generated hook")

    check = os.path.join(project, CHECK_REL)
    if not _has_check_command(check):
        p.notes.append(NO_CHECK_NOTE.format(path=check))

    link = os.path.join(project, SKILLS_LINK_REL)
    skills = os.path.join(project, SKILLS_TARGET_REL)
    if os.path.isdir(skills) and not os.path.islink(skills) and not os.path.lexists(link):
        p.links.append((link, os.path.join("..", SKILLS_TARGET_REL)))
    return p


def not_executable(paths):
    """Written hooks that exist but cannot run: git skips a pre-push hook without the executable bit."""
    return [x for x in paths if os.path.isfile(x) and not os.access(x, os.X_OK)]
