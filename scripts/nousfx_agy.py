"""nousfx_agy: generate the agy (Antigravity CLI) plugin files. Used by nousfx_sync.py.

Sync owns one folder, <home>/.gemini/config/plugins/nousfx/:
  plugin.json       the plugin manifest
  rules/AGENTS.md   generated header + neutral rules + agy overlay + local.md + local.agy.md
(skills/<name> links come from nousfx_skills.plan). Nothing else under .gemini is touched.
"""
import hashlib
import json
import os
import re

PLUGIN_REL = os.path.join(".gemini", "config", "plugins", "nousfx")
MAX_BYTES = 24000

CLAUDE_ONLY_TERMS = (
    r"Skill tool", r"ToolSearch", r"\bOpus\b", r"\bHaiku\b", r"\bFable\b", r"\bSonnet\b",
    r"\bExplore\b", r"CLAUDE\.md", r"~/\.claude", r"/goal\b", r"review-gate\.py",
    r"subagent_type", r"Claude Code",
)


def plugin_dir(home):
    return os.path.join(home, PLUGIN_REL)


def claude_only_terms(text):
    """The Claude-only terms found in text, in CLAUDE_ONLY_TERMS order."""
    return [t for t in CLAUDE_ONLY_TERMS if re.search(t, text)]


def _read(path):
    try:
        with open(path, encoding="utf-8") as f:
            return f.read()
    except FileNotFoundError:
        return None


def build_rules(repo, state, SyncError):
    sources = [("neutral rules", os.path.join(repo, "harness", "AGENTS.md"), True),
               ("agy overlay", os.path.join(repo, "harness", "overlays", "agy.overlay.md"), True),
               ("local file", os.path.join(state, "local.md"), False),
               ("agy local file", os.path.join(state, "local.agy.md"), False)]
    parts, digest = [], hashlib.sha256()
    for label, path, required in sources:
        text = _read(path)
        if text is None:
            if required:
                raise SyncError(f"missing {label}: {path}", 2)
            continue
        parts.append(text.strip("\n"))
        digest.update(f"{label}\0{text}\0".encode("utf-8"))
    header = (f"<!-- generated by nousfx_sync src:{digest.hexdigest()[:12]}. "
              "Do not edit; change the sources and re-run. -->")
    out = header + "\n\n" + "\n\n".join(parts) + "\n"
    size = len(out.encode("utf-8"))
    if size > MAX_BYTES:
        raise SyncError(f"agy rules are {size} bytes, over the {MAX_BYTES} byte limit. "
                        "Shorten the sources. Nothing was written.", 2)
    return out


def manifest_text():
    """plugin.json text. Also used for a project's plugin folder, which carries only MCP."""
    manifest = {"name": "nousfx", "description": "NousFX rules and skills, generated by nousfx_sync"}
    return json.dumps(manifest, indent=2) + "\n"


def plan_agy(repo, home, state, SyncError):
    """{absolute path: text} for plugin.json and rules/AGENTS.md."""
    base = plugin_dir(home)
    return {os.path.join(base, "plugin.json"): manifest_text(),
            os.path.join(base, "rules", "AGENTS.md"): build_rules(repo, state, SyncError)}
