"""nousfx_agents: generate Claude Code agent files from role-based neutral sources.

An agent in <repo>/harness/agents/*.md names a role (fast, strong, deep) in its frontmatter
instead of a model:

    role: strong

<repo>/harness/models.toml maps each role, per tool, to a model and an effort level. The generator
replaces the `role:` line with `model:` and `effort:` lines (an `effort:` already in the agent
wins) and adds a generated header after the frontmatter. Everything else is copied untouched.
"""
import os
import re

TOOL = "claude"


def _parse_toml(text):
    """tomllib on Python 3.11+, else a tiny reader for [a.b] tables of key = "string"."""
    try:
        import tomllib
        return tomllib.loads(text)
    except ImportError:
        pass
    data, table = {}, None
    for n, raw in enumerate(text.splitlines(), 1):
        line = raw.strip()
        if not line or line.startswith("#"):
            continue
        m = re.fullmatch(r"\[([\w.-]+)\]", line)
        if m:
            table = data
            for part in m.group(1).split("."):
                table = table.setdefault(part, {})
            continue
        m = re.fullmatch(r'([\w-]+)\s*=\s*"([^"]*)"\s*(?:#.*)?', line)
        if not m or table is None:
            raise ValueError(f"line {n}: unsupported syntax")
        table[m.group(1)] = m.group(2)
    return data


def load_roles(repo, error):
    path = os.path.join(repo, "harness", "models.toml")
    try:
        with open(path, encoding="utf-8") as f:
            data = _parse_toml(f.read())
    except FileNotFoundError:
        raise error(f"missing models file: {path}", 2)
    except ValueError as e:
        raise error(f"{path} is not valid TOML ({e})", 2)
    return data.get(TOOL, {})


def render(name, source, roles, header, error):
    parts = source.split("\n---\n", 1)
    if not source.startswith("---\n") or len(parts) != 2:
        raise error(f"agent {name}: no frontmatter", 2)
    front_lines = parts[0].split("\n")
    body = parts[1]
    role_lines = [i for i, l in enumerate(front_lines) if l.startswith("role:")]
    if len(role_lines) != 1:
        raise error(f"agent {name}: needs exactly one `role:` line in its frontmatter", 2)
    role = front_lines[role_lines[0]].split(":", 1)[1].strip()
    if role not in roles or "model" not in roles[role]:
        known = ", ".join(sorted(roles)) or "none"
        raise error(f"agent {name}: unknown role '{role}' for {TOOL} "
                    f"(roles in harness/models.toml: {known})", 2)
    out = [f"model: {roles[role]['model']}"]
    if not any(l.startswith("effort:") for l in front_lines) and "effort" in roles[role]:
        out.append(f"effort: {roles[role]['effort']}")
    front_lines[role_lines[0]:role_lines[0] + 1] = out
    return "\n".join(front_lines) + "\n---\n\n" + header + "\n" + body


def plan_agents(repo, claude_dir, commit, error):
    """Map of absolute path -> generated text. Empty when the repo has no harness/agents."""
    src = os.path.join(repo, "harness", "agents")
    if not os.path.isdir(src):
        return {}
    roles = load_roles(repo, error)
    header = (f"<!-- generated by nousfx_sync {commit}. "
              "Do not edit; change harness/agents and harness/models.toml and re-run. -->")
    wanted = {}
    for fname in sorted(os.listdir(src)):
        if not fname.endswith(".md"):
            continue
        with open(os.path.join(src, fname), encoding="utf-8") as f:
            text = f.read()
        wanted[os.path.join(claude_dir, "agents", fname)] = render(fname[:-3], text, roles, header, error)
    return wanted
