#!/usr/bin/env python3
"""Tests for role-based agents in nousfx_sync. Run: python3 -B scripts/test_nousfx_agents.py

Same seam as test_nousfx_sync: the sync CLI as a subprocess against a temp home, temp state home
and a temp copy of the sources (the real harness/agents and harness/models.toml).
"""
import glob
import os
import re
import shutil
import subprocess
import sys
import unittest

sys.dont_write_bytecode = True
import test_nousfx_sync as tsync

ROOT = tsync.ROOT
read, write = tsync.read, tsync.write

# The intended differences between generated agents and claude/agents/*.md. Keep this list small.
#  1. A generated header comment follows the frontmatter of each file.
HEADER = re.compile(r"^<!-- generated by nousfx_sync [^\n]* -->\n\n", re.M)


class AgentBase(tsync.Base):
    def setUp(self):
        super().setUp()
        shutil.copytree(os.path.join(ROOT, "harness", "agents"), os.path.join(self.repo, "harness", "agents"))
        shutil.copy(os.path.join(ROOT, "harness", "models.toml"), os.path.join(self.repo, "harness", "models.toml"))
        self.agents = os.path.join(self.home, ".claude", "agents")

    def agent(self, name):
        return read(os.path.join(self.agents, name + ".md"))

    def listing(self):
        return sorted(os.listdir(self.agents)) if os.path.isdir(self.agents) else []


class Golden(AgentBase):
    def test_generated_agents_match_todays_files_except_the_header(self):
        r = self.sync()
        self.assertEqual(r.returncode, 0, r.stderr)
        today = sorted(os.path.basename(p) for p in glob.glob(os.path.join(ROOT, "claude", "agents", "*.md")))
        self.assertEqual(self.listing(), today)
        for name in today:
            generated = read(os.path.join(self.agents, name))
            self.assertRegex(generated, HEADER, name)
            self.assertEqual(HEADER.sub("", generated, count=1),
                             read(os.path.join(ROOT, "claude", "agents", name)), name)

    def test_header_comes_after_the_frontmatter(self):
        self.sync()
        self.assertTrue(self.agent("reviewer").startswith("---\nname: reviewer\n"))


class Mapping(AgentBase):
    def test_changing_a_model_changes_only_that_roles_agents(self):
        self.sync()
        before = {n: self.agent(n[:-3]) for n in self.listing()}
        models = os.path.join(self.repo, "harness", "models.toml")
        write(models, read(models).replace('model = "opus"', 'model = "opus-next"'))
        r = self.sync()
        self.assertEqual(r.returncode, 0, r.stderr)
        after = {n: self.agent(n[:-3]) for n in self.listing()}
        changed = [n for n in before if before[n] != after[n]]
        self.assertEqual(changed, ["reviewer-high.md", "reviewer.md"])  # both have role: strong
        self.assertIn("model: opus-next\n", after["reviewer.md"])

    def test_review_tier_agents_get_their_model_and_effort(self):
        """NFX-63: Tier 0 and 1 use reviewer-light, Tier 2 reviewer, Tier 3 reviewer-high."""
        self.sync()
        for name, model, effort in (("reviewer-light", "sonnet", "medium"), ("reviewer", "opus", "medium"),
                                    ("reviewer-high", "opus", "high")):
            text = self.agent(name)
            self.assertIn(f"\nmodel: {model}\n", text, name)
            self.assertEqual(len(re.findall(r"^effort:", text, re.M)), 1, name)
            self.assertIn(f"\neffort: {effort}\n", text, name)

    def test_implementer_is_a_balanced_agent_with_its_limits_ladder_and_duties(self):
        """NFX-129: Sonnet builds ready-for-agent S/M tickets; the description carries dispatch, ladder, duties."""
        self.sync()
        text = self.agent("implementer")
        self.assertIn("\nmodel: sonnet\n", text)
        self.assertEqual(len(re.findall(r"^effort:", text, re.M)), 1)
        self.assertIn("\neffort: medium\n", text)
        self.assertRegex(text, r"(?m)^maxTurns: \d+$")
        description = re.search(r"(?m)^description: (.*)$", text).group(1)
        for phrase in ("ready-for-agent", "size S or M", "size L", "migrations", "/via check",
                       "long chain of dependent steps",  # the limits
                       "On FAILED", "effort high", "take the ticket over on Opus",  # the ladder
                       "no edits while it runs", "git status and HEAD show no commit", "review marker",
                       "read the full diff", "tier.py", "tier 3", "ui true",  # the main session's duties
                       "Review fixes stay with you"):
            self.assertIn(phrase, description, phrase)
        body = text.split("-->", 1)[1]
        for phrase in ("DONE", "FAILED", "Changed files", "Proofs", "Open decisions",  # the return format
                       "git commit", "git push", "review-gate.py", "--mark"):  # forbidden by name
            self.assertIn(phrase, body, phrase)

    def test_the_balanced_role_is_its_own_entry(self):
        self.sync()
        models = os.path.join(self.repo, "harness", "models.toml")
        write(models, read(models).replace('model = "sonnet"', 'model = "sonnet-next"'))
        self.sync()
        self.assertIn("model: sonnet-next\n", self.agent("reviewer-light"))
        self.assertIn("model: opus\n", self.agent("reviewer"))

    def test_unknown_role_fails_and_writes_nothing(self):
        path = os.path.join(self.repo, "harness", "agents", "reviewer.md")
        write(path, read(path).replace("role: strong", "role: gigantic"))
        r = self.sync()
        self.assertNotEqual(r.returncode, 0)
        self.assertIn("gigantic", r.stderr)
        self.assertIn("reviewer", r.stderr)
        self.assertEqual(self.tree(), {})
        self.assertFalse(os.path.exists(self.state + "/backups"))

    def test_agent_without_a_role_fails(self):
        path = os.path.join(self.repo, "harness", "agents", "reviewer.md")
        write(path, read(path).replace("role: strong\n", ""))
        r = self.sync()
        self.assertNotEqual(r.returncode, 0)
        self.assertEqual(self.tree(), {})


class AgentDrift(AgentBase):
    def header(self, name):
        return self.agent(name).split("<!--", 1)[1].split("-->", 1)[0]

    def test_an_unrelated_commit_is_not_drift(self):
        env = {**os.environ, "GIT_CONFIG_GLOBAL": os.devnull, "GIT_CONFIG_SYSTEM": os.devnull}

        def vcs(*args):
            subprocess.run(["git", "-C", self.repo, "-c", "user.name=t", "-c", "user.email=t@t", *args],
                           check=True, capture_output=True, env=env)
        vcs("init", "-q")
        vcs("add", "-A")
        vcs("commit", "-qm", "one")
        self.assertEqual(self.sync().returncode, 0)
        write(os.path.join(self.repo, "unrelated.txt"), "x")
        vcs("add", "-A")
        vcs("commit", "-qm", "two")
        self.assertEqual(self.sync("--check").returncode, 0)

    def test_header_follows_the_agent_source_and_its_role_only(self):
        self.sync()
        before = {n[:-3]: self.header(n[:-3]) for n in self.listing()}
        models = os.path.join(self.repo, "harness", "models.toml")
        write(models, read(models).replace('model = "opus"', 'model = "opus-next"'))
        self.sync()
        after = {n[:-3]: self.header(n[:-3]) for n in self.listing()}
        self.assertEqual(sorted(n for n in before if before[n] != after[n]), ["reviewer", "reviewer-high"])
        path = os.path.join(self.repo, "harness", "agents", "reviewer.md")
        write(path, read(path) + "\nExtra line.\n")
        self.assertEqual(self.sync("--check").returncode, 1)
        self.sync()
        self.assertNotEqual(self.header("reviewer"), after["reviewer"])


class Modes(AgentBase):
    def test_second_run_changes_nothing(self):
        self.sync()
        before = self.snapshot()
        r = self.sync()
        self.assertEqual(r.returncode, 0, r.stderr)
        self.assertEqual(self.snapshot(), before)

    def test_dry_run_writes_nothing_and_shows_agents(self):
        r = self.sync("--dry-run")
        self.assertEqual(r.returncode, 0, r.stderr)
        self.assertIn("agents/reviewer.md", r.stdout)
        self.assertEqual(self.tree(), {})

    def test_check_reports_agent_drift(self):
        self.assertEqual(self.sync("--check").returncode, 1)
        self.sync()
        self.assertEqual(self.sync("--check").returncode, 0)
        write(os.path.join(self.agents, "reviewer.md"), "edited\n")
        r = self.sync("--check")
        self.assertEqual(r.returncode, 1)
        self.assertIn("agents/reviewer.md", r.stdout)

    def test_restore_removes_new_agents_and_restores_edited_ones(self):
        self.sync()
        write(os.path.join(self.agents, "reviewer.md"), "mine\n")
        self.sync()  # overwrites the edit, backing it up
        self.assertEqual(self.sync("--restore").returncode, 0)
        self.assertEqual(self.agent("reviewer"), "mine\n")
        self.assertEqual(self.sync("--restore").returncode, 0)
        self.assertEqual(self.listing(), [])

    def test_repo_without_agents_still_syncs(self):
        shutil.rmtree(os.path.join(self.repo, "harness", "agents"))
        r = self.sync()
        self.assertEqual(r.returncode, 0, r.stderr)
        self.assertEqual(self.listing(), [])


if __name__ == "__main__":
    unittest.main()
