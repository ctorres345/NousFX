#!/usr/bin/env python3
"""Tests for install.sh, the wrapper that only runs the sync. Run: python3 -B scripts/test_install_wrapper.py

install.sh runs as a subprocess with --home and --state-home pointing at temp folders, never the real home.
install.ps1 cannot run here; the test only checks it has no copy code and forwards its arguments.
"""
import json
import os
import shutil
import subprocess
import tempfile
import unittest

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
INSTALL_SH = os.path.join(ROOT, "install.sh")
INSTALL_PS1 = os.path.join(ROOT, "install.ps1")


class InstallWrapper(unittest.TestCase):
    def setUp(self):
        self.home = os.path.realpath(tempfile.mkdtemp(prefix="nousfx-install-test-"))
        self.addCleanup(shutil.rmtree, self.home, ignore_errors=True)
        self.state = os.path.join(self.home, "state")

    def offline_repo(self):
        """A copy of the harness with an empty skills lock, so a real run fetches nothing from GitHub."""
        repo = os.path.join(self.home, "repo")
        for d in ("claude", "harness"):
            shutil.copytree(os.path.join(ROOT, d), os.path.join(repo, d), ignore=shutil.ignore_patterns("__pycache__"))
        with open(os.path.join(repo, "harness", "skills.lock.json"), "w", encoding="utf-8") as f:
            json.dump({"version": 1, "skills": {}}, f)
        return repo

    def run_sh(self, answer, *extra):
        env = {"PATH": os.environ["PATH"], "HOME": self.home}
        args = ["bash", INSTALL_SH, "--home", self.home, "--state-home", self.state, *extra]
        return subprocess.run(args, input=answer, capture_output=True, text=True, env=env, cwd=self.home)

    def test_no_answer_runs_the_dry_run_and_writes_nothing(self):
        r = self.run_sh("n\n")
        self.assertEqual(r.returncode, 0, r.stderr)
        self.assertIn("Nothing written", r.stdout)
        self.assertFalse(os.path.exists(os.path.join(self.home, ".claude")))
        self.assertFalse(os.path.exists(self.state))

    def test_closed_stdin_counts_as_no(self):
        r = self.run_sh("")
        self.assertEqual(r.returncode, 0, r.stderr)
        self.assertIn("Nothing written", r.stdout)
        self.assertFalse(os.path.exists(os.path.join(self.home, ".claude")))

    def test_yes_writes_the_rules_and_the_gate(self):
        r = self.run_sh("y\n", "--repo", self.offline_repo())
        self.assertEqual(r.returncode, 0, r.stderr)
        claude = os.path.join(self.home, ".claude")
        with open(os.path.join(claude, "CLAUDE.md"), encoding="utf-8") as f:
            self.assertTrue(f.readline().startswith("<!-- generated by nousfx_sync "))
        self.assertTrue(os.path.isfile(os.path.join(claude, "hooks", "review-gate.py")))

    def test_an_answer_without_a_newline_still_counts(self):
        r = self.run_sh("y", "--repo", self.offline_repo())
        self.assertEqual(r.returncode, 0, r.stderr)
        self.assertTrue(os.path.isfile(os.path.join(self.home, ".claude", "CLAUDE.md")))

    def test_a_failing_dry_run_stops_before_asking(self):
        r = self.run_sh("y\n", "--tools", "nonsense")
        self.assertNotEqual(r.returncode, 0)
        self.assertNotIn("Apply these changes", r.stdout)
        self.assertFalse(os.path.exists(os.path.join(self.home, ".claude")))

    def test_the_scripts_hold_no_copy_code(self):
        for path in (INSTALL_SH, INSTALL_PS1):
            with open(path, encoding="utf-8") as f:
                text = f.read()
            self.assertIn("nousfx_sync.py", text)
            self.assertLess(len(text.splitlines()), 30, path)
            for word in ("cp ", "Copy-Item", "settings.json", "find "):
                self.assertNotIn(word, text, f"{os.path.basename(path)} must only run the sync ({word!r})")

    def test_the_powershell_script_forwards_its_arguments_to_both_runs(self):
        with open(INSTALL_PS1, encoding="utf-8") as f:
            text = f.read()
        self.assertEqual(text.count("@fwd"), 2)
        self.assertNotIn("@args", text)
        self.assertIn("-join ','", text)  # claude,agy arrives as an array in PowerShell
        self.assertIn("--dry-run", text)


if __name__ == "__main__":
    unittest.main()
