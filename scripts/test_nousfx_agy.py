#!/usr/bin/env python3
"""Tests for nousfx_agy and the extra_roots link root of nousfx_skills. Run: python3 -B scripts/test_nousfx_agy.py

Modules are called directly against a temp home, temp state and a temp repo. Nothing real is touched.
"""
import json
import os
import shutil
import sys
import tempfile
import unittest

sys.dont_write_bytecode = True
HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import nousfx_agy as agy  # noqa: E402
import nousfx_skills as skills  # noqa: E402
from nousfx_sync import SyncError  # noqa: E402
from test_nousfx_sync import read, write  # noqa: E402

ROOT = os.path.dirname(HERE)


class Base(unittest.TestCase):
    def setUp(self):
        self.tmp = os.path.realpath(tempfile.mkdtemp(prefix="nousfx-agy-test-"))
        self.addCleanup(shutil.rmtree, self.tmp, ignore_errors=True)
        self.home, self.state, self.repo = (os.path.join(self.tmp, d) for d in ("home", "state", "repo"))
        os.makedirs(self.home)
        os.makedirs(self.state)
        for rel in ("AGENTS.md", os.path.join("overlays", "agy.overlay.md"), os.path.join("agy", "agy_gate.py")):
            write(os.path.join(self.repo, "harness", rel), read(os.path.join(ROOT, "harness", rel)))
        for name in agy.GATE_FILES:
            write(os.path.join(self.repo, "claude", "hooks", name), read(os.path.join(ROOT, "claude", "hooks", name)))

    def src(self, *rel):
        return os.path.join(self.repo, "harness", *rel)

    def rules(self):
        return agy.plan_agy(self.repo, self.home, self.state, SyncError)[
            os.path.join(agy.plugin_dir(self.home), "rules", "AGENTS.md")]


class Rules(Base):
    def test_paths_and_manifest(self):
        out = agy.plan_agy(self.repo, self.home, self.state, SyncError)
        base = os.path.join(self.home, ".gemini", "config", "plugins", "nousfx")
        self.assertEqual(sorted(out), sorted(os.path.join(base, *rel) for rel in (
            ("plugin.json",), ("rules", "AGENTS.md"), ("hooks.json",), ("hooks", "agy_gate.py"),
            ("hooks", "review-gate.py"), ("hooks", "pr_create_parser.py"))))
        self.assertIn('"name": "nousfx"', out[os.path.join(base, "plugin.json")])
        self.assertTrue(out[os.path.join(base, "plugin.json")].endswith("\n"))

    def test_order_neutral_overlay_locals(self):
        write(os.path.join(self.state, "local.md"), "LOCAL-ONE\n")
        write(os.path.join(self.state, "local.agy.md"), "LOCAL-AGY\n")
        write(os.path.join(self.state, "local.claude.md"), "LOCAL-CLAUDE\n")
        text = self.rules()
        self.assertTrue(text.startswith("<!-- generated by nousfx_sync src:"))
        self.assertNotIn("LOCAL-CLAUDE", text)
        pos = [text.index(read(self.src("AGENTS.md")).strip("\n")),
               text.index(read(self.src("overlays", "agy.overlay.md")).strip("\n").replace(agy.REPO_PLACEHOLDER, self.repo)),
               text.index("LOCAL-ONE"), text.index("LOCAL-AGY")]
        self.assertEqual(pos, sorted(pos))

    def test_overlay_gets_the_clone_path_and_no_placeholder_is_left(self):
        text = self.rules()
        self.assertIn(f'"{self.repo}/scripts/nousfx_sync.py" --check --summary --tools agy', text)
        self.assertNotIn(agy.REPO_PLACEHOLDER, text)

    def test_placeholder_in_a_local_file_is_left_alone(self):
        write(os.path.join(self.state, "local.md"), "keep {{NOUSFX_REPO}} as typed\n")
        self.assertIn("keep {{NOUSFX_REPO}} as typed", self.rules())

    def test_no_claude_only_terms_with_real_harness(self):
        self.assertEqual(agy.claude_only_terms(self.rules()), [])

    def test_claude_only_terms_finds_them(self):
        found = agy.claude_only_terms("use the Skill tool, then Opus and ~/.claude/x")
        self.assertEqual(len(found), 3)
        self.assertEqual(agy.claude_only_terms("plain text"), [])

    def test_header_hash_changes_with_source(self):
        first = self.rules().split("\n", 1)[0]
        write(self.src("overlays", "agy.overlay.md"), read(self.src("overlays", "agy.overlay.md")) + "more\n")
        self.assertNotEqual(first, self.rules().split("\n", 1)[0])

    def test_cap_raises(self):
        write(os.path.join(self.state, "local.md"), "x" * 24000)
        with self.assertRaises(SyncError) as cm:
            self.rules()
        self.assertIn("24000", str(cm.exception))

    def test_missing_sources_raise_code_2(self):
        for rel in (("AGENTS.md",), ("overlays", "agy.overlay.md")):
            path = self.src(*rel)
            saved = read(path)
            os.remove(path)
            with self.assertRaises(SyncError) as cm:
                self.rules()
            self.assertEqual(cm.exception.code, 2)
            write(path, saved)


class Hooks(Base):
    def plan(self, **kw):
        return agy.plan_agy(self.repo, self.home, self.state, SyncError, **kw)

    def test_hooks_json_runs_the_adapter_from_the_plugin_folder(self):
        base = agy.plugin_dir(self.home)
        cfg = json.loads(self.plan()[os.path.join(base, "hooks.json")])
        (name, events), = cfg.items()
        (entry,) = events["PreToolUse"]
        self.assertEqual(entry["matcher"], "run_command|.*create_pull_request")
        (hook,) = entry["hooks"]
        self.assertEqual(hook["type"], "command")
        adapter = os.path.join(base, "hooks", "agy_gate.py")
        self.assertTrue(hook["command"].startswith(f'python3 -I -B "{adapter}" --expect '), hook["command"])
        hashes = hook["command"].rsplit(" ", 1)[1].split(",")
        plan = self.plan()
        self.assertEqual(hashes, [agy.sha256(plan[os.path.join(base, "hooks", n)])
                                  for n in ("agy_gate.py", "review-gate.py", "pr_create_parser.py")])
        self.assertGreaterEqual(hook["timeout"], 30)

    def test_command_uses_the_given_interpreter_and_path(self):
        out = self.plan(python="python", native=lambda p: p.replace(os.sep, "/") + ".x")
        cfg = json.loads(out[os.path.join(agy.plugin_dir(self.home), "hooks.json")])
        command = cfg[next(iter(cfg))]["PreToolUse"][0]["hooks"][0]["command"]
        self.assertTrue(command.startswith('python -I -B "') and 'agy_gate.py.x" --expect ' in command, command)

    def test_hook_files_are_copies_of_the_sources(self):
        out = self.plan()
        hooks = os.path.join(agy.plugin_dir(self.home), "hooks")
        self.assertEqual(out[os.path.join(hooks, "agy_gate.py")], read(self.src("agy", "agy_gate.py")))
        for name in agy.GATE_FILES:
            self.assertEqual(out[os.path.join(hooks, name)], read(os.path.join(self.repo, "claude", "hooks", name)))

    def test_missing_source_raises_code_2(self):
        for path in (self.src("agy", "agy_gate.py"), os.path.join(self.repo, "claude", "hooks", "review-gate.py")):
            os.rename(path, path + ".off")
            with self.assertRaises(SyncError) as cm:
                self.plan()
            self.assertEqual(cm.exception.code, 2)
            os.rename(path + ".off", path)

    def test_self_test_passes_on_the_real_adapter_and_fails_on_a_broken_one(self):
        out = self.plan()
        for path, text in out.items():
            write(path, text)
        agy.self_test(agy.plugin_dir(self.home), SyncError)  # does not raise
        write(os.path.join(agy.plugin_dir(self.home), "hooks", "agy_gate.py"), "import sys\nsys.exit(0)\n")
        with self.assertRaises(SyncError) as cm:
            agy.self_test(agy.plugin_dir(self.home), SyncError)
        self.assertIn("self-test failed", str(cm.exception))


class SelfTestEnvironment(Base):
    def test_inherited_git_variables_do_not_reach_the_decoy_repo(self):
        """Run from a git hook, GIT_DIR points at another repo: the self-test must not commit there."""
        import subprocess
        import nousfx_sync
        decoy = os.path.join(self.tmp, "decoy")
        os.makedirs(decoy)
        subprocess.run(["git", "init", "-q", "-b", "decoy/main"], cwd=decoy, check=True, capture_output=True)
        for path, text in agy.plan_agy(self.repo, self.home, self.state, SyncError).items():
            write(path, text)
        hook = os.path.join(self.home, ".claude", "hooks")
        for name in agy.GATE_FILES:
            write(os.path.join(hook, name), read(os.path.join(ROOT, "claude", "hooks", name)))
        saved = dict(os.environ)
        os.environ["GIT_DIR"] = os.path.join(decoy, ".git")
        try:
            agy.self_test(agy.plugin_dir(self.home), SyncError)
            nousfx_sync.self_test(os.path.join(hook, "review-gate.py"))
        finally:
            os.environ.clear()
            os.environ.update(saved)
        log = subprocess.run(["git", "log", "--oneline"], cwd=decoy, capture_output=True, text=True)
        self.assertNotEqual(log.returncode, 0, "the decoy repo got a commit: " + log.stdout)  # still unborn


class ExtraRoot(Base):
    def setUp(self):
        super().setUp()
        for name in ("alpha", "beta"):
            write(os.path.join(self.repo, "claude", "skills", name, "SKILL.md"), f"# {name}\n")
        self.root = os.path.join(agy.plugin_dir(self.home), "skills")
        self.agents = os.path.join(self.home, ".agents", "skills")
        self.backup = os.path.join(self.tmp, "backup")

    def plan(self):
        return skills.plan(self.repo, self.home, self.state, extra_roots=(self.root,))

    def apply(self, p):
        skills.apply(p, self.backup, False, self.state)

    def test_third_link_per_skill_and_idempotent(self):
        p = self.plan()
        self.assertEqual(len(p.actions), 6)
        self.apply(p)
        for name in ("alpha", "beta"):
            link = os.path.join(self.root, name)
            self.assertTrue(os.path.islink(link))
            self.assertEqual(os.readlink(link), os.path.join(self.agents, name))
            self.assertTrue(os.path.isfile(os.path.join(link, "SKILL.md")))
        self.assertFalse(self.plan().actions)

    def test_default_has_no_plugin_link(self):
        self.assertEqual(len(skills.plan(self.repo, self.home, self.state).actions), 4)

    def test_collision_reported_and_skill_skipped(self):
        write(os.path.join(self.root, "alpha", "SKILL.md"), "# mine\n")
        p = self.plan()
        self.assertEqual(p.collisions, [("alpha", os.path.join(self.root, "alpha"))])
        self.apply(p)
        self.assertFalse(os.path.lexists(os.path.join(self.agents, "alpha")))
        self.assertTrue(os.path.islink(os.path.join(self.root, "beta")))
        self.assertEqual(read(os.path.join(self.root, "alpha", "SKILL.md")), "# mine\n")

    def test_undo_removes_plugin_links(self):
        self.apply(self.plan())
        skills.undo(self.backup, self.state)
        self.assertFalse(os.path.lexists(os.path.join(self.root, "alpha")))
        self.assertFalse(os.path.lexists(os.path.join(self.agents, "alpha")))


if __name__ == "__main__":
    unittest.main()
