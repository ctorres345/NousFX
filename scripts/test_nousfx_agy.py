#!/usr/bin/env python3
"""Tests for nousfx_agy and the extra_roots link root of nousfx_skills. Run: python3 -B scripts/test_nousfx_agy.py

Modules are called directly against a temp home, temp state and a temp repo. Nothing real is touched.
"""
import os
import shutil
import sys
import tempfile
import unittest

sys.dont_write_bytecode = True
HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import nousfx_agy as agy  # noqa: E402
import nousfx_skills as skills  # noqa: E402
from nousfx_sync import SyncError  # noqa: E402
from test_nousfx_sync import read, write  # noqa: E402

ROOT = os.path.dirname(HERE)


class Base(unittest.TestCase):
    def setUp(self):
        self.tmp = os.path.realpath(tempfile.mkdtemp(prefix="nousfx-agy-test-"))
        self.addCleanup(shutil.rmtree, self.tmp, ignore_errors=True)
        self.home, self.state, self.repo = (os.path.join(self.tmp, d) for d in ("home", "state", "repo"))
        os.makedirs(self.home)
        os.makedirs(self.state)
        for rel in ("AGENTS.md", os.path.join("overlays", "agy.overlay.md")):
            write(os.path.join(self.repo, "harness", rel), read(os.path.join(ROOT, "harness", rel)))

    def src(self, *rel):
        return os.path.join(self.repo, "harness", *rel)

    def rules(self):
        return agy.plan_agy(self.repo, self.home, self.state, SyncError)[
            os.path.join(agy.plugin_dir(self.home), "rules", "AGENTS.md")]


class Rules(Base):
    def test_paths_and_manifest(self):
        out = agy.plan_agy(self.repo, self.home, self.state, SyncError)
        base = os.path.join(self.home, ".gemini", "config", "plugins", "nousfx")
        self.assertEqual(sorted(out), [os.path.join(base, "plugin.json"), os.path.join(base, "rules", "AGENTS.md")])
        self.assertIn('"name": "nousfx"', out[os.path.join(base, "plugin.json")])
        self.assertTrue(out[os.path.join(base, "plugin.json")].endswith("\n"))

    def test_order_neutral_overlay_locals(self):
        write(os.path.join(self.state, "local.md"), "LOCAL-ONE\n")
        write(os.path.join(self.state, "local.agy.md"), "LOCAL-AGY\n")
        write(os.path.join(self.state, "local.claude.md"), "LOCAL-CLAUDE\n")
        text = self.rules()
        self.assertTrue(text.startswith("<!-- generated by nousfx_sync src:"))
        self.assertNotIn("LOCAL-CLAUDE", text)
        pos = [text.index(read(self.src("AGENTS.md")).strip("\n")),
               text.index(read(self.src("overlays", "agy.overlay.md")).strip("\n")),
               text.index("LOCAL-ONE"), text.index("LOCAL-AGY")]
        self.assertEqual(pos, sorted(pos))

    def test_no_claude_only_terms_with_real_harness(self):
        self.assertEqual(agy.claude_only_terms(self.rules()), [])

    def test_claude_only_terms_finds_them(self):
        found = agy.claude_only_terms("use the Skill tool, then Opus and ~/.claude/x")
        self.assertEqual(len(found), 3)
        self.assertEqual(agy.claude_only_terms("plain text"), [])

    def test_header_hash_changes_with_source(self):
        first = self.rules().split("\n", 1)[0]
        write(self.src("overlays", "agy.overlay.md"), read(self.src("overlays", "agy.overlay.md")) + "more\n")
        self.assertNotEqual(first, self.rules().split("\n", 1)[0])

    def test_cap_raises(self):
        write(os.path.join(self.state, "local.md"), "x" * 24000)
        with self.assertRaises(SyncError) as cm:
            self.rules()
        self.assertIn("24000", str(cm.exception))

    def test_missing_sources_raise_code_2(self):
        for rel in (("AGENTS.md",), ("overlays", "agy.overlay.md")):
            path = self.src(*rel)
            saved = read(path)
            os.remove(path)
            with self.assertRaises(SyncError) as cm:
                self.rules()
            self.assertEqual(cm.exception.code, 2)
            write(path, saved)


class ExtraRoot(Base):
    def setUp(self):
        super().setUp()
        for name in ("alpha", "beta"):
            write(os.path.join(self.repo, "claude", "skills", name, "SKILL.md"), f"# {name}\n")
        self.root = os.path.join(agy.plugin_dir(self.home), "skills")
        self.agents = os.path.join(self.home, ".agents", "skills")
        self.backup = os.path.join(self.tmp, "backup")

    def plan(self):
        return skills.plan(self.repo, self.home, self.state, extra_roots=(self.root,))

    def apply(self, p):
        skills.apply(p, self.backup, False, self.state)

    def test_third_link_per_skill_and_idempotent(self):
        p = self.plan()
        self.assertEqual(len(p.actions), 6)
        self.apply(p)
        for name in ("alpha", "beta"):
            link = os.path.join(self.root, name)
            self.assertTrue(os.path.islink(link))
            self.assertEqual(os.readlink(link), os.path.join(self.agents, name))
            self.assertTrue(os.path.isfile(os.path.join(link, "SKILL.md")))
        self.assertFalse(self.plan().actions)

    def test_default_has_no_plugin_link(self):
        self.assertEqual(len(skills.plan(self.repo, self.home, self.state).actions), 4)

    def test_collision_reported_and_skill_skipped(self):
        write(os.path.join(self.root, "alpha", "SKILL.md"), "# mine\n")
        p = self.plan()
        self.assertEqual(p.collisions, [("alpha", os.path.join(self.root, "alpha"))])
        self.apply(p)
        self.assertFalse(os.path.lexists(os.path.join(self.agents, "alpha")))
        self.assertTrue(os.path.islink(os.path.join(self.root, "beta")))
        self.assertEqual(read(os.path.join(self.root, "alpha", "SKILL.md")), "# mine\n")

    def test_undo_removes_plugin_links(self):
        self.apply(self.plan())
        skills.undo(self.backup, self.state)
        self.assertFalse(os.path.lexists(os.path.join(self.root, "alpha")))
        self.assertFalse(os.path.lexists(os.path.join(self.agents, "alpha")))


if __name__ == "__main__":
    unittest.main()
