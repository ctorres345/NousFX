#!/usr/bin/env python3
"""Tests for the guard at the top of install.sh. Run: python3 -B scripts/test_install_guard.py

install.sh runs as a subprocess against a temp HOME. It is retired by NFX-48, so only the guard is covered.
"""
import os
import shutil
import subprocess
import tempfile
import unittest

HERE = os.path.dirname(os.path.abspath(__file__))
INSTALL = os.path.join(os.path.dirname(HERE), "install.sh")
HEADER = "<!-- generated by nousfx_sync src:0123456789ab. Do not edit; change the sources and re-run. -->"


class InstallGuard(unittest.TestCase):
    def setUp(self):
        self.home = os.path.realpath(tempfile.mkdtemp(prefix="nousfx-install-test-"))
        self.addCleanup(shutil.rmtree, self.home, ignore_errors=True)
        self.rules = os.path.join(self.home, ".claude", "CLAUDE.md")
        os.makedirs(os.path.dirname(self.rules))

    def install(self, *args):
        env = {"PATH": os.environ["PATH"], "HOME": self.home}
        return subprocess.run(["bash", INSTALL, *args], capture_output=True, text=True, env=env, cwd=self.home)

    def write(self, text):
        with open(self.rules, "w", encoding="utf-8") as f:
            f.write(text)

    def test_refuses_when_sync_owns_the_rules_file(self):
        text = HEADER + "\n\n# Rules\n"
        self.write(text)
        r = self.install()
        self.assertNotEqual(r.returncode, 0)
        self.assertIn("nousfx_sync", r.stderr)
        self.assertIn("--force", r.stderr)
        with open(self.rules, encoding="utf-8") as f:
            self.assertEqual(f.read(), text)
        self.assertEqual(os.listdir(os.path.join(self.home, ".claude")), ["CLAUDE.md"])  # nothing installed

    def test_force_installs_anyway(self):
        self.write(HEADER + "\n\n# Rules\n")
        r = self.install("--force")
        self.assertEqual(r.returncode, 0, r.stderr)
        self.assertTrue(os.path.isdir(os.path.join(self.home, ".claude", "hooks")))

    def test_a_hand_written_rules_file_is_not_blocked(self):
        self.write("# My rules\n")
        r = self.install()
        self.assertEqual(r.returncode, 0, r.stderr)

    def test_no_rules_file_is_not_blocked(self):
        self.assertFalse(os.path.exists(self.rules))
        self.assertEqual(self.install().returncode, 0)


if __name__ == "__main__":
    unittest.main()
