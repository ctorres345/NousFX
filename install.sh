#!/usr/bin/env bash
# Installs the shared Claude Code config into ~/.claude (agents, skills, hooks).
# Existing files are backed up as <file>.bak-<timestamp> before being replaced.
# Agents, skills and hooks reached through a symlink are skipped. settings.json is still written
# through one, so a dotfiles-managed copy keeps getting updates. Rules come from nousfx_sync, not here.
set -euo pipefail

SRC="$(cd "$(dirname "${BASH_SOURCE[0]}")/claude" && pwd)"
DEST="${CLAUDE_HOME:-$HOME/.claude}"
STAMP="$(date +%Y%m%d-%H%M%S)"
SKIPPED=0

# nousfx_sync owns CLAUDE.md once it has written its generated header, and this script no longer writes
# rules. Refuse on a synced machine, where the old agents, skills and hooks would fight the sync, unless
# --force is given. A leftover "# Delegation policy" section goes away at the first sync.
if [ "${1:-}" != "--force" ] && [ -f "$DEST/CLAUDE.md" ] \
  && head -n 1 "$DEST/CLAUDE.md" | grep -q '^<!-- generated by nousfx_sync '; then
  echo "install.sh: $DEST/CLAUDE.md was generated by nousfx_sync, which owns these files." \
    "Run scripts/nousfx_sync.py instead, or pass --force to install anyway." >&2
  exit 1
fi

# Print the symlink on the way from $DEST to $DEST/<rel>, if any. A linked skill or hook
# (for example one from ~/.agents/skills) belongs to someone else; writing through it would overwrite it.
linked_path() {
  local rel="$1"
  while [ "$rel" != . ]; do
    if [ -L "$DEST/$rel" ]; then
      echo "$rel"
      return 0
    fi
    rel="$(dirname "$rel")"
  done
  return 1
}

install_file() {
  local rel="$1" link
  if link="$(linked_path "$rel")"; then
    echo "warning: skipped $rel ($link is a symlink, left untouched)" >&2
    SKIPPED=$((SKIPPED + 1))
    return
  fi
  mkdir -p "$(dirname "$DEST/$rel")"
  if [ -e "$DEST/$rel" ] && ! cmp -s "$SRC/$rel" "$DEST/$rel"; then
    cp "$DEST/$rel" "$DEST/$rel.bak-$STAMP"
    echo "backed up $rel"
  fi
  cp "$SRC/$rel" "$DEST/$rel"
  echo "installed $rel"
}

while IFS= read -r -d '' f; do
  install_file "${f#"$SRC"/}"
done < <(find "$SRC/agents" "$SRC/skills" "$SRC/hooks" -type f -print0)

# Register the PR review gate in settings.json (idempotent; other settings and hooks untouched).
PY=python3; command -v python3 >/dev/null 2>&1 && python3 -c 'import sys' 2>/dev/null || PY=python
case "$(uname -s)" in MINGW*|MSYS*|CYGWIN*) WIN=1; GATE="$(cygpath -m "$DEST")/hooks/review-gate.py";; *) WIN=0; GATE="$DEST/hooks/review-gate.py";; esac
[ -e "$DEST/settings.json" ] && cp "$DEST/settings.json" "$DEST/settings.json.bak-$STAMP"
"$PY" - "$DEST/settings.json" "$GATE" "$WIN" <<'PYEOF'
import json, os, sys
path, gate, win = sys.argv[1], sys.argv[2], sys.argv[3] == "1"
cfg = json.load(open(path, encoding="utf-8")) if os.path.exists(path) else {}
hook = {"type": "command", "timeout": 30,
        "command": f'python "{gate}"' if win else f'python3 "{gate}"'}
if win:
    hook["shell"] = "powershell"
entry = {"matcher": "Bash|PowerShell|mcp__.*create_pull_request", "hooks": [hook]}
pre = cfg.setdefault("hooks", {}).setdefault("PreToolUse", [])
pre[:] = [e for e in pre if not any("review-gate.py" in h.get("command", "") for h in e.get("hooks", []))]
pre.append(entry)
json.dump(cfg, open(path, "w", encoding="utf-8"), indent=2, ensure_ascii=False)
print("registered review-gate hook in settings.json")
PYEOF

if command -v claude >/dev/null 2>&1; then
  echo "Claude Code version: $(claude --version) (Haiku 5.5 needs 2.1.293 or later)"
fi
if [ "$SKIPPED" -gt 0 ]; then
  echo "warning: $SKIPPED file(s) skipped behind symlinks. Update them at the link target; a skipped" \
    "hooks/pr_create_parser.py makes the review gate block every gh pr command." >&2
fi
echo "Done. Run /agents in a new session to confirm."

if [ -f "$DEST/CLAUDE.md" ] && grep -q '^# Delegation policy$' "$DEST/CLAUDE.md" \
  && ! head -n 1 "$DEST/CLAUDE.md" | grep -q '^<!-- generated by nousfx_sync '; then
  echo "note: $DEST/CLAUDE.md still has an old '# Delegation policy' section that install.sh no longer updates." \
    "Run scripts/nousfx_sync.py to generate the rules."
fi
